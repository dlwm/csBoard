import fs from 'node:fs/promises';
import path from 'node:path';
import Ajv from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { BUILTIN_COMMAND_NAMES, describeViewerContract } from '../packages/viewer/src/core/contract.js';
// Ahead-of-time validators preserve strict CSP. No runtime eval/Function.
// 中文：Schema 是权威来源，静态生成校验器，CI 检查生成物是否同步。
const ajv=new Ajv({strict:false,strictNumbers:true,allErrors:false,code:{source:true,esm:true}}),names={},lookup={},schemas=new Map();
for(const profile of ['standalone','application']) {
 const contract=describeViewerContract({apiVersion:'0.2',profile,names:BUILTIN_COMMAND_NAMES});
 for(const [kind,entries] of [['command',contract.commands],['event',contract.events]])for(const entry of entries) {
  const key=`${profile}:${kind}:${entry.name}`,schema=kind==='command'?entry.parameters:entry.payloadSchema,signature=JSON.stringify(schema);
  let name=schemas.get(signature);
  if(!name){name=`contract${Object.keys(names).length}`;ajv.addSchema(schema,key);names[name]=key;schemas.set(signature,name);}
  lookup[key]=name;
 }
}
let code=standaloneCode(ajv,names),deps=new Map();
code=code.replace(/require\("(ajv\/dist\/runtime\/[^"\n]+)"\)\.default/g,(_,module)=>{if(!deps.has(module))deps.set(module,`runtime${deps.size}`);return deps.get(module);});
const imports=[...deps].map(([module,name])=>`import ${name}Module from '${module}.js';\nconst ${name} = ${name}Module.default || ${name}Module;`).join('\n');
const text=`// Generated by scripts/sync-viewer-contracts.js; do not edit.\n${imports}\n${code}\nexport const VALIDATORS = {${Object.entries(lookup).map(([key,name])=>`${JSON.stringify(key)}:${name}`).join(',')}};\n`;
const file=path.resolve('packages/viewer/src/core/generated/validators.js');
if(process.argv.includes('--check')) {if(await fs.readFile(file,'utf8').catch(()=>null)!==text)throw Error('Viewer schemas changed; run make viewer-contracts');}
else {await fs.mkdir(path.dirname(file),{recursive:true});await fs.writeFile(file,text);}
console.log(`Viewer contracts ${process.argv.includes('--check')?'checked':'generated'}: ${Object.keys(names).length} validators`);
